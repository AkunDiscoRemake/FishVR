// Generates single-file versions of the migrations and Edge Functions for pasting into the Supabase dashboard.
import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const mig = 'supabase/migrations';
writeFileSync('supabase/dashboard/ALL_MIGRATIONS.sql',
  readdirSync(mig).filter((f) => f.endsWith('.sql')).sort().map((f) => `-- ===== ${f}\n` + readFileSync(`${mig}/${f}`, 'utf8')).join('\n'));
for (const fn of ['fishing-start', 'fishing-complete', 'shop', 'pvp']) {
  await build({
    entryPoints: [`supabase/functions/${fn}/index.ts`], bundle: true, format: 'esm', platform: 'neutral',
    target: 'es2022', external: ['npm:*'], outfile: `supabase/dashboard/${fn}.ts`, logLevel: 'warning',
    banner: { js: `// GENERATED by npm run build:dashboard from supabase/functions/${fn} - paste into the Supabase dashboard as function "${fn}".` },
  });
}
// one minified file containing all four functions (routes by function name in the URL)
await build({
  entryPoints: ['supabase/dashboard/src/game-server.ts'], bundle: true, format: 'esm', platform: 'neutral',
  target: 'es2022', external: ['npm:*'], minify: true, outfile: 'supabase/dashboard/game-server.ts', logLevel: 'warning',
});
console.log('supabase/dashboard updated');
